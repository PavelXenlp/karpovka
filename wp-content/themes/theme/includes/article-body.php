          <h2 id="eco">Эко-дома</h2>
          <p><span class="gold-header"><em>Эко-дома</em></span> — фишка Карповки. Это отдельные деревянные домики на берегу Карпова пруда с панорамными окнами, террасой и видом на воду. Каждый дом рассчитан на 2–4 человека и включает спальню, гостиную зону, мини-кухню и собственную санузел. Интерьер выдержан в скандинавском стиле: натуральное дерево, нейтральные тона, много света.</p>
          <p>Эко-дома идеально подходят для пар, которые ценят приватность и романтику. Утром вы просыпаетесь от пения птиц, выходите на террасу с кофе и смотрите, как туман стелется над прудом. Вечером — костёр у воды или горячая ванна под звёздами. Незабываемые впечатления гарантированы.</p>

