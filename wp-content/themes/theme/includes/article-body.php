          <h2 id="guest">Гостевые дома</h2>
          <p><span class="gold-header"><em>Гостевые дома</em></span> — золотая середина для компаний и больших семей. Это двухэтажные дома с 3–4 комнатами, общей гостиной, полностью оборудованной кухней и barbecue-зоной во дворе. Каждый дом вмещает до 8–10 человек, что делает их идеальными для семейных торжеств, дней рождения и корпоративов.</p>
          <p>В гостевых домах есть всё необходимое для комфортного проживания: Wi-Fi, телевизор, холодильник, микроволновка, посуда. При этом вы находитесь на территории парк-отеля и можете пользоваться всеми его услугами — от бассейна до конных прогулок.</p>

