          <h2 id="hotel">Гостиничный комплекс</h2>
          <p><span class="gold-header"><em>Гостиничные номера</em></span> — классический вариант для тех, кто предпочитает отельный комфорт. Комплекс расположен в главном здании парк-отеля, рядом с СПА-центром, кафе и баней. Номера категории «Стандарт» и «Комфорт» оформлены в современном стиле с элементами эко-дизайна.</p>
          <p>Главные преимущества: ежедневная уборка, возможность заказать завтрак в номер, быстрая доступность всех услуг отеля без выхода на улицу. Отличный выбор для деловых поездок, коротких визитов и гостей, которые планируют много времени проводить в СПА.</p>

