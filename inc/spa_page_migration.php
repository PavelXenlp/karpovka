function karpovka_migrate_spa_page_data( $post_id ) {
    if ( get_post_meta( $post_id, '_karpovka_spa_page_migrated_20260824', true ) ) return false;

    foreach ( karpovka_spa_page_migration_data() as $key => $value ) {
        update_post_meta( $post_id, $key, $value );
    }
    update_post_meta( $post_id, '_karpovka_spa_page_migrated_20260824', '1' );
    return true;
}

function karpovka_migrate_spa_section_variants( $post_id ) {
