function karpovka_migrate_events_page_data( $post_id ) {
    if ( get_post_meta( $post_id, '_karpovka_events_page_migrated_20260901_2', true ) ) return false;

    foreach ( karpovka_events_page_migration_data() as $key => $value ) {
        update_post_meta( $post_id, $key, $value );
    }

    update_post_meta( $post_id, '_karpovka_section_order', [ 'hero', 'formats', 'details', 'weekend', 'included', 'price', 'gallery', 'reviews', 'articles', 'faq', 'cta' ] );
    update_post_meta( $post_id, '_karpovka_hidden_sections', [] );
    update_post_meta( $post_id, '_karpovka_events_page_migrated_20260901_2', '1' );
    return true;
}

