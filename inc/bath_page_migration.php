    foreach ( karpovka_bath_page_migration_data() as $key => $value ) {
        update_post_meta( $post_id, $key, $value );
    }

    update_post_meta( $post_id, '_karpovka_section_order', [ 'hero', 'types', 'details', 'price', 'gallery', 'reviews', 'faq', 'cta', 'articles' ] );
