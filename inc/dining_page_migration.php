function karpovka_migrate_dining_page_data( $post_id ) {
    if ( get_post_meta( $post_id, '_karpovka_dining_page_migrated_20260901', true ) ) return false;

    foreach ( karpovka_dining_page_migration_data() as $key => $value ) {
        update_post_meta( $post_id, $key, $value );
    }

    update_post_meta( $post_id, '_karpovka_section_order', [ 'hero', 'details', 'menu', 'formats', 'gallery', 'booking', 'reviews', 'articles', 'faq', 'cta' ] );
    update_post_meta( $post_id, '_karpovka_hidden_sections', [] );
    update_post_meta( $post_id, '_karpovka_dining_page_migrated_20260901', '1' );
    return true;
}

